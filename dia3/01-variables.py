# USO DE VARIABLES
# Las variables son contenedores para almacenar datos en la memoria del ordenador.
# En Python, no es necesario declarar el tipo de variable, ya que es un lenguaje de tipado dinámico.
# Se pueden asignar valores a las variables utilizando el operador '='.
# Ejemplo de asignación de variables
nombre = "Juan" # Variable de tipo cadena (string)
edad = 30 # Variable de tipo entero (int)
altura = 1.75 # Variable de tipo flotante (float)
